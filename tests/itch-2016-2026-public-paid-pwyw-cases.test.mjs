 assert.equal(a.paid_checkout_conversion,null);
 assert.equal(b.source_publisher_june6_reported_cumulative_copies,5000);
 assert.equal(b.reported_prior_to_steam_launch,true);
 assert.equal(b.steam_launch_date,'2026-06-26');
