import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const load=p=>JSON.parse(fs.readFileSync(new URL('../'+p,import.meta.url),'utf8'));
test('Repeat game purchase and external renewal protocol defines denominators, censored periods and privacy',()=>{
 const d=load('ontology/itch-io/repeat-buyer-and-membership-measurement-2026.json');
 const spec=load('specimens/itch-io.json');
 const queue=load('queues/itch-io.json');
 const p=load('plans/itch-io.json');
 const ids=new Set(spec.evidence.map(s=>s.id));
 assert(d.source_ids.every(id=>ids.has(id)));
 assert.deepEqual(d.horizons_days,[30,90,365]);
 assert(d.definitions.some(x=>x.id==='repeat_paid_customer'&&x.denominator.includes('eligible_for_full_horizon')));
 assert(d.definitions.some(x=>x.id==='external_patreon_churn_rate'&&x.denominator.includes('at_risk')));
 assert(d.definitions.some(x=>x.id==='external_patreon_renewal_rate'&&x.denominator.includes('due_for_renewal')));
 assert(d.cohort_rules.some(x=>/right.censored/i.test(x)));
 for(const route of d.routes)assert(route.source_ids.length&&route.source_ids.every(id=>ids.has(id)));
 assert.equal(d.routes.find(x=>x.id==='itch_followers').money_flow,'attention_or_notifications_not_receipts');
 assert.equal(d.routes.find(x=>x.id==='patreon_tier_access_via_itch').paid_order_possible,false);
 assert.equal(d.privacy.raw_buyer_identifiers_collected_for_this_study,false);
 assert.equal(d.privacy.cross_platform_person_level_joining_performed,false);
 assert.equal(d.experiment_limits.launched,false);
 assert(Object.values(d.unknown).every(v=>v===null));
 const task=queue.queues.flatMap(x=>x.tasks).find(x=>x.id==='strategy/repeat-test');
 assert.equal(task.progress,100);assert.equal(task.status,'complete');
 for(const x of ['ontology/itch-io/repeat-buyer-and-membership-measurement-2026.json','ontology/itch-io/repeat-buyer-and-membership-measurement-2026.md','tests/itch-io-repeat-purchase-and-churn-protocol.test.mjs','specimens/itch-io.json'])assert(task.evidence.includes(x));
 assert.equal(p.total_tracked_tasks,244);assert.equal(p.detail_tasks.length,160);
 const mean=(queue.queues.flatMap(x=>x.tasks).reduce((a,x)=>a+x.progress,0)+p.detail_tasks.reduce((a,x)=>a+x.percent,0))/244;
 assert.equal(p.progress_percent,Math.round(mean));
});
